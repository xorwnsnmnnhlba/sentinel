-- 설정 변경 이력 (누가·언제·무엇을). 프로젝트·환경·스위트·케이스·스케줄·사용자·초대의 등록·수정·삭제
-- 값은 남기지 않고 바뀐 항목 이름만 (fields). 시크릿은 이름만 (secrets.token)
-- 항목을 삭제(보관)해도 이력을 읽을 수 있도록 당시 이름(target_name) 보관. 실행 기록은 test_run이 담당
-- 행은 추가만 하고 수정·삭제하지 않음

CREATE TABLE change_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id    BIGINT,
    target_type VARCHAR(20)  NOT NULL,
    target_id   BIGINT       NOT NULL,
    target_name VARCHAR(320) NOT NULL,
    project_id  BIGINT,
    action      VARCHAR(20)  NOT NULL,
    fields      JSON         NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

-- 항목별 이력 (항목 화면), 프로젝트별 이력 (프로젝트 화면·전체 목록 필터). 최신순
CREATE INDEX idx_change_log_target ON change_log (target_type, target_id, id DESC);
CREATE INDEX idx_change_log_project ON change_log (project_id, id DESC);
