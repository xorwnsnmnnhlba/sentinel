-- 환경별 점검 시간. 이 시간 동안 그 환경의 스케줄 실행을 건너뜀 (실행 기록·실패 알림 없음). 끝나면 따로 조치 없이 다시 실행
-- 배포·점검으로 예상된 실패가 알림·통과율에 섞이는 것 방지. 스케줄을 끄고 다시 켜는 것을 잊는 일도 방지
-- 취소·조기 종료는 삭제(보관, archived_at). 누가 등록·변경했는지는 change_log

CREATE TABLE maintenance_window (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    environment_id BIGINT       NOT NULL,
    starts_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    ends_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    reason         VARCHAR(200),
    created_by     BIGINT,
    archived_at    TIMESTAMP(6) WITH TIME ZONE,
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

-- 스케줄 실행 전 환경의 진행 중 점검 확인, 환경별 진행 중·예정 점검 목록 (끝나지 않은 것만)
CREATE INDEX idx_maintenance_environment ON maintenance_window (environment_id, ends_at);
