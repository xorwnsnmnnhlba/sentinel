-- 사용자와 로그인 세션. 가입은 관리자 초대로만 (공개 가입 없음)
-- - 비밀번호는 BCrypt 해시로만 저장. 평문·복호화 가능한 형태 미사용
-- - 세션 토큰도 해시로 저장. DB 유출만으로 남의 세션을 쓸 수 없도록 함
-- - 외래키 미사용 원칙에 따라 user_id는 인덱스만 유지

CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL,
    name          VARCHAR(100) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    archived_at   TIMESTAMP(6) WITH TIME ZONE,
    archive_key   BIGINT DEFAULT 0 NOT NULL,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_app_user_email UNIQUE (email, archive_key)
);

CREATE TABLE user_session (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash   VARCHAR(100) NOT NULL,
    user_id      BIGINT       NOT NULL,
    expires_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    last_used_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_user_session_token UNIQUE (token_hash)
);

CREATE INDEX idx_user_session_user ON user_session (user_id);
