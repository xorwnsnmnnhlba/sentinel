-- CI 등 자동화용 API 토큰. 실행 시작·결과 조회만 가능 (그 외 API는 403)
-- 토큰 원문은 발급 응답에만 전달하고 SHA-256 해시로 저장. 표시용으로 앞 8자(token_prefix)만 보관
-- 만료는 발급 때 30·90·180·365일 중 선택 (만료 없는 토큰 없음). 폐기는 revoked_at

CREATE TABLE access_token (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL,
    name         VARCHAR(100) NOT NULL,
    token_hash   VARCHAR(100) NOT NULL,
    token_prefix VARCHAR(12)  NOT NULL,
    expires_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    last_used_at TIMESTAMP(6) WITH TIME ZONE,
    revoked_at   TIMESTAMP(6) WITH TIME ZONE,
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_access_token_hash UNIQUE (token_hash)
);

CREATE INDEX idx_access_token_user ON access_token (user_id);
