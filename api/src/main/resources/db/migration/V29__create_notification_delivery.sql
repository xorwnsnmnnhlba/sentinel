-- 알림 발송 이력. 발송 1건마다 시각·채널·제목·결과 ("알림이 안 왔다"를 확인하는 곳)
-- Webhook 주소(자격증명)와 본문은 남기지 않음
-- channel: DEFAULT(서버 기본 채널) / PROJECT(프로젝트 Webhook, project_id 있음)
-- format: SLACK / TEAMS / TEXT / LOG(기본 채널 주소 미설정, 서버 로그에만 기록)
-- delivered: 2xx 응답을 받음(LOG는 기록됨). status_code: 받은 응답의 상태 코드, error: 응답을 받지 못한 사유(TIMEOUT 등)
-- 보관기간(sentinel.retention.notification-retention, 기본 90일)이 지나면 정리 배치에서 삭제

CREATE TABLE notification_delivery (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sent_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    channel     VARCHAR(10)                 NOT NULL,
    project_id  BIGINT,
    format      VARCHAR(10)                 NOT NULL,
    title       VARCHAR(300)                NOT NULL,
    tone        VARCHAR(10)                 NOT NULL,
    delivered   BOOLEAN                     NOT NULL,
    status_code INTEGER,
    error       VARCHAR(40),
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_notification_delivery_sent_at ON notification_delivery (sent_at);
