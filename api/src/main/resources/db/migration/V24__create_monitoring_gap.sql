-- 모니터링 공백. 스케줄이 예정 시각에서 기준 시간(sentinel.schedule.gap-threshold) 넘게 늦게 실행된 기간
-- Sentinel 중지·서버 절전·DB 연결 끊김·오래 걸린 앞 실행 등으로 폴링이 멈췄던 기간을 폴링 재개 시 기록
-- started_at: 늦은 스케줄 중 가장 이른 예정 시각, ended_at: 폴링 재개 시각
-- 기준 시간 안에 이어진 공백은 한 건으로 합침 (missed_schedules는 가장 많았던 수)

CREATE TABLE monitoring_gap (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    ended_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    missed_schedules INTEGER                     NOT NULL,
    created_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_monitoring_gap_ended_at ON monitoring_gap (ended_at);
