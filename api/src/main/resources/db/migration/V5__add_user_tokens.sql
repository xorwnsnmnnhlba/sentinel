-- 초대·비밀번호 재설정 링크에 쓰이는 1회용 토큰
-- - 토큰 원문은 링크 발급 시에만 전달하고 저장은 해시로만 함
-- - 초대는 아직 계정이 없으므로 email·role을 함께 보관, 재설정은 user_id 사용
-- - 사용·만료된 토큰은 남겨 두고(used_at 기록) 재사용만 차단

CREATE TABLE user_token (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash VARCHAR(100) NOT NULL,
    type       VARCHAR(20)  NOT NULL,
    email      VARCHAR(255),
    role       VARCHAR(20),
    user_id    BIGINT,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    used_at    TIMESTAMP(6) WITH TIME ZONE,
    created_by BIGINT       NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_user_token_hash UNIQUE (token_hash)
);

CREATE INDEX idx_user_token_user ON user_token (user_id);
