-- 초기 스키마. Hibernate가 현재 엔티티로 생성한 DDL 기준으로 정리 (ddl-auto: validate로 일치 검증)
-- 스키마(sentinel)는 Flyway가 생성·지정하므로 테이블명에 스키마 접두어 미사용
-- enum 컬럼의 값 목록 CHECK 제약은 미사용. 값 검증은 애플리케이션 enum 담당, enum 값 추가 시 마이그레이션 불필요

CREATE TABLE project (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_project_name UNIQUE (name)
);

CREATE TABLE environment (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  BIGINT       NOT NULL,
    name        VARCHAR(50)  NOT NULL,
    base_url    VARCHAR(500) NOT NULL,
    variables   JSONB        NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_environment_project_name UNIQUE (project_id, name),
    CONSTRAINT fk_environment_project FOREIGN KEY (project_id) REFERENCES project (id)
);

CREATE TABLE test_suite (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  BIGINT       NOT NULL,
    name        VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_test_suite_project_name UNIQUE (project_id, name),
    CONSTRAINT fk_test_suite_project FOREIGN KEY (project_id) REFERENCES project (id)
);

CREATE TABLE test_case (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    suite_id    BIGINT        NOT NULL,
    name        VARCHAR(200)  NOT NULL,
    method      VARCHAR(10)   NOT NULL,
    path        VARCHAR(2000) NOT NULL,
    headers     JSONB         NOT NULL,
    body        TEXT,
    assertions  JSONB,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_test_case_suite_name UNIQUE (suite_id, name),
    CONSTRAINT fk_test_case_suite FOREIGN KEY (suite_id) REFERENCES test_suite (id)
);

CREATE TABLE test_run (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    suite_id       BIGINT      NOT NULL,
    environment_id BIGINT      NOT NULL,
    trigger        VARCHAR(20) NOT NULL,
    status         VARCHAR(20) NOT NULL,
    started_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    finished_at    TIMESTAMP(6) WITH TIME ZONE,
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_test_run_suite FOREIGN KEY (suite_id) REFERENCES test_suite (id),
    CONSTRAINT fk_test_run_environment FOREIGN KEY (environment_id) REFERENCES environment (id)
);

CREATE INDEX idx_run_suite_time ON test_run (suite_id, started_at DESC);

CREATE TABLE test_result (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id                  BIGINT        NOT NULL,
    test_case_id            BIGINT        NOT NULL,
    outcome                 VARCHAR(20)   NOT NULL,
    verdict                 VARCHAR(10),
    assertion_results       JSONB,
    error_reason            VARCHAR(30),
    error_message           VARCHAR(1000),
    request_method          VARCHAR(10)   NOT NULL,
    request_url             VARCHAR(2000),
    request_headers         JSONB,
    request_body            TEXT,
    status_code             INTEGER,
    response_headers        JSONB,
    response_body           TEXT,
    response_body_truncated BOOLEAN       NOT NULL,
    elapsed_ms              BIGINT,
    created_at              TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at              TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_test_result_run FOREIGN KEY (run_id) REFERENCES test_run (id),
    CONSTRAINT fk_test_result_test_case FOREIGN KEY (test_case_id) REFERENCES test_case (id)
);

CREATE INDEX idx_result_run ON test_result (run_id);
CREATE INDEX idx_result_case_time ON test_result (test_case_id, id DESC);

CREATE TABLE test_schedule (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    suite_id          BIGINT       NOT NULL,
    environment_id    BIGINT       NOT NULL,
    cron              VARCHAR(100) NOT NULL,
    enabled           BOOLEAN      NOT NULL,
    next_run_at       TIMESTAMP(6) WITH TIME ZONE,
    last_triggered_at TIMESTAMP(6) WITH TIME ZONE,
    created_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_test_schedule_suite FOREIGN KEY (suite_id) REFERENCES test_suite (id),
    CONSTRAINT fk_test_schedule_environment FOREIGN KEY (environment_id) REFERENCES environment (id)
);

CREATE INDEX idx_schedule_due ON test_schedule (enabled, next_run_at);
