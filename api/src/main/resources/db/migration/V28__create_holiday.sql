-- 휴일. 등록한 날짜(sentinel.schedule.zone 기준)에는 "휴일 건너뛰기"를 켠 스케줄 실행을 건너뜀 (실행 기록·알림 없음)
-- 공휴일·대체 공휴일·사내 휴무를 관리자가 화면에서 등록. 삭제는 보관(archived_at), 사용 중인 날짜끼리만 중복 불가(archive_key)

CREATE TABLE holiday (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    holiday_date DATE                        NOT NULL,
    name         VARCHAR(100)                NOT NULL,
    created_by   BIGINT,
    archived_at  TIMESTAMP(6) WITH TIME ZONE,
    archive_key  BIGINT                      NOT NULL DEFAULT 0,
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_holiday_date UNIQUE (holiday_date, archive_key)
);

