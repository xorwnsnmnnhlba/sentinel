-- 응답시간 악화 알림. 케이스·환경별 p95가 기준 이상 나빠지면 1건 열고(알림), 다시 기준 아래로 돌아오면 닫음(회복 알림)
-- 한 케이스·환경에 열린 알림(resolved_at null)은 최대 1건. 느린 동안은 다시 알리지 않음
-- baseline_p95: 감지 당시 비교 기간(그 전 7일) p95. 회복 판단은 이 값 기준 (비교 기간이 느린 값을 흡수해도 회복으로 보지 않도록)

CREATE TABLE slowdown_alert (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    test_case_id    BIGINT                      NOT NULL,
    environment_id  BIGINT                      NOT NULL,
    baseline_p95    BIGINT                      NOT NULL,
    detected_p95    BIGINT                      NOT NULL,
    detected_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    resolved_at     TIMESTAMP(6) WITH TIME ZONE,
    resolved_p95    BIGINT,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_slowdown_alert_open ON slowdown_alert (resolved_at, test_case_id, environment_id);
