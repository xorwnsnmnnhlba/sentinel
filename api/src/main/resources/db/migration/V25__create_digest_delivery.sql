-- 주간 요약 알림 발송 기록. 예정 시각(scheduled_at)마다 1건으로 같은 요약의 중복 발송 방지
-- 예정 시각에 Sentinel이 꺼져 있었으면 켜진 뒤 1회 발송 (7일 이내). 발송 실패도 기록이 남아 다시 보내지 않음
-- period_from·period_to: 요약 기간 (sentinel.schedule.zone 기준 날짜, 포함)

CREATE TABLE digest_delivery (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scheduled_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    period_from  DATE                        NOT NULL,
    period_to    DATE                        NOT NULL,
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_digest_delivery_scheduled_at UNIQUE (scheduled_at)
);
